def is_indo_european(entry: Mapping[str, object]) -> bool:
    """Whether an entry's language belongs to the Indo-European family.

    Args:
        entry: A parsed Wiktextract entry.

    Returns:
        True if entry["lang"] is a known Indo-European language name.
    """
    return entry.get("lang") in INDO_EUROPEAN_LANGUAGES


def filter_indo_european(
    entries: Iterable[Mapping[str, object]],
) -> Iterator[Mapping[str, object]]:
    """Yield only entries whose language is Indo-European.

    Args:
        entries: Parsed Wiktextract entries, any language.

    Yields:
        Entries whose `lang` is a known Indo-European language name.
    """
    for entry in entries:
        if is_indo_european(entry):
            yield entry
